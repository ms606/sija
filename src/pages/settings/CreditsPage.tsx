import { ExternalLink } from 'lucide-react'
import { Card, CardTitle } from '../../components/ui/Card'
import { Fi } from '../../components/ui/FiText'
import { PageHeader } from '../../components/ui/PageHeader'
import { DATA_SOURCES, SOFTWARE, VERIFICATION_TOOLS } from '../../data/credits'
import { grammar } from '../../services/grammar'
import { ILLUSTRATION_IDS } from '../../components/media/illustration-art'

function Ext({ href, children }: { href: string; children: React.ReactNode }) {
  return (
    <a href={href} target="_blank" rel="noreferrer" className="inline-flex items-center gap-1 font-semibold text-primary hover:underline">
      {children}
      <ExternalLink aria-hidden className="size-3.5" />
    </a>
  )
}

export default function CreditsPage() {
  const photos = grammar.lexicon.filter((l) => l.image?.photo)
  return (
    <div className="mx-auto max-w-3xl space-y-5">
      <PageHeader
        title="Credits and licences"
        fi="Lähteet ja lisenssit"
        why="Every source is listed with its own terms, exactly as the provider states them. Nothing on this page is a general licence claim."
      />

      <Card className="space-y-4">
        <CardTitle>Word data</CardTitle>
        {DATA_SOURCES.map((s) => (
          <div key={s.id} className="space-y-1.5">
            <p className="font-semibold">
              <Fi>{s.title}</Fi> — {s.provider}
            </p>
            <p className="text-sm">{s.use}</p>
            {s.modifications && <p className="text-sm text-muted">{s.modifications}</p>}
            <p className="text-sm">
              Licence: {s.licenseUrl ? <Ext href={s.licenseUrl}>{s.licenseName}</Ext> : s.licenseName}
            </p>
            <blockquote className="rounded-lg border-l-4 border-border-strong bg-surface-2 p-2 text-sm" lang="fi">
              {s.attributionText}
            </blockquote>
            <p className="text-sm">
              <Ext href={s.sourceUrl}>Source page</Ext> · retrieved {s.retrievedAt}
            </p>
          </div>
        ))}
      </Card>

      <Card className="space-y-2">
        <CardTitle>Grammar engine, sentences and explanations</CardTitle>
        <p className="text-sm">
          The grammar engine, the {grammar.lexicon.length} word entries, the example sentences, lessons and explanations were written for this app. Every
          noun form shown is generated by the engine; its case forms were compared by machine with independent sources (see below).
        </p>
        <p className="text-sm text-muted">
          Native-speaker review of the example sentences is still pending; each sentence records whether it has been reviewed.
        </p>
      </Card>

      <Card className="space-y-2">
        <CardTitle>Pictures</CardTitle>
        <ul className="list-disc space-y-1 pl-5 text-sm">
          <li>{ILLUSTRATION_IDS.length} line illustrations were drawn for this app as original SVG artwork.</li>
          <li>Emoji are characters drawn by your device’s own font; no emoji images are included.</li>
          <li>
            {photos.length === 0
              ? 'This version contains no photographs. Any photo added later will be listed here with its own author, licence and source.'
              : `${photos.length} photographs, each credited below.`}
          </li>
        </ul>
        {photos.length > 0 && (
          <ul className="space-y-2 text-sm">
            {photos.map((l) => {
              const c = l.image!.photo!.credit
              return (
                <li key={l.id}>
                  <Fi className="font-semibold">{l.lemma}</Fi>: {c.attributionText} — {c.licenseUrl ? <Ext href={c.licenseUrl}>{c.licenseName}</Ext> : c.licenseName}
                  {c.modifications && <span className="text-muted"> ({c.modifications})</span>} · <Ext href={c.sourceUrl}>source</Ext>
                </li>
              )
            })}
          </ul>
        )}
      </Card>

      <Card className="space-y-2">
        <CardTitle>Audio</CardTitle>
        <p className="text-sm">Speech is produced by your device’s own text-to-speech voice. No audio is recorded, stored or sent anywhere.</p>
      </Card>

      <Card className="space-y-2">
        <CardTitle>Software and typeface</CardTitle>
        <ul className="space-y-1 text-sm">
          {SOFTWARE.map((s) => (
            <li key={s.name}>
              <Ext href={s.url}>{s.name}</Ext> — {s.license}
            </li>
          ))}
        </ul>
      </Card>

      <Card className="space-y-2">
        <CardTitle sub="Used only while developing the app. Nothing from these tools is included in it.">Verification tools</CardTitle>
        <ul className="space-y-2 text-sm">
          {VERIFICATION_TOOLS.map((t) => (
            <li key={t.title}>
              <Ext href={t.url}>{t.title}</Ext> — {t.provider}. {t.licenseName}. <span className="text-muted">{t.note}</span>
            </li>
          ))}
        </ul>
      </Card>
    </div>
  )
}
