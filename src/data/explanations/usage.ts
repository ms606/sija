import type { CaseId, NumberId } from '../../types/content'

/**
 * "Why this case here?" — the reason a sentence's focus noun has its case
 * (and number). A reason is a reusable template; each annotated sentence names
 * its reason and, where the reason depends on a trigger word, that word (`cue`)
 * exactly as it appears in the sentence. Tests check that the cue is really in
 * the sentence and that the reason fits the token's case and number.
 *
 * These are curated, machine-checked annotations: like the sentences
 * themselves, they still await native-speaker review.
 *
 * Template placeholders: {form} the focus form, {lemma}, {g} the first gloss,
 * {a} "a doctor", {the} "the doctor", {pl} "doctors", {cue} the trigger word,
 * {cueGloss} its meaning, {note} the sentence-specific note.
 */
export interface UsageReason {
  /** Short heading, e.g. "After an amount word". */
  title: string
  /** Cases this reason can explain. */
  cases: readonly CaseId[]
  number?: NumberId
  /** The template needs a trigger word from the sentence. */
  needsCue?: boolean
  /** The template needs a sentence-specific note. */
  needsNote?: boolean
  /** The template already explains the number, so no plural note is added. */
  explainsNumber?: boolean
  /** Only for words whose place nouns take the outer cases (asema, tori, mökki …). */
  outerPlace?: boolean
  why: string
}

