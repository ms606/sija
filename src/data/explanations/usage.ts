export interface SentenceUsage {
  reason: UsageReasonId
  /** The trigger word as written in the sentence. */
  cue?: string
  /** Sentence-specific note (required by `fixed`, added after the reason otherwise). */
  note?: string
  /** The English sense of the word in this sentence, when it is not the first gloss (lehti: "newspaper", not "leaf"). */
  sense?: string
  /** Why a plural is used when it does not simply mean "more than one". */
  numberNote?: string
  /** A contrasting sentence and what the difference shows. */
  compare?: { sentenceId: string; note: string }
}

const u = (reason: UsageReasonId, cue?: string, extra: Omit<SentenceUsage, 'reason' | 'cue'> = {}): SentenceUsage => ({
  reason,
  ...(cue ? { cue } : {}),
  ...extra,
})

