/**
 * Photo pipeline (dev-only). For every manifest entry:
 *   1. reads the file's own metadata from the Commons API (extmetadata),
 *   2. rejects it unless the metadata is complete, unrestricted, and the licence
 *      is one we accept (a policy list — no licence is assumed or generalised),
 *   3. downloads a 500 px thumbnail into public/images/nouns/,
 *   4. writes src/data/images/photos.ts with one verbatim MediaCredit per photo.
 * Usage: npm run images:fetch
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { imageInfo, metaValue, politeFetch, type CommonsImage } from './commons-api.ts'

/** Licences we accept, exactly as Commons writes LicenseShortName. Anything else is rejected. */
const ACCEPTED = new Set([
  'CC0',
  'Public domain',
  'CC BY 2.0',
  'CC BY 2.5',
  'CC BY 3.0',
  'CC BY 4.0',
  'CC BY-SA 2.0',
  'CC BY-SA 2.5',
  'CC BY-SA 3.0',
  'CC BY-SA 4.0',
])
const THUMB = 500
const OUT_DIR = 'public/images/nouns'
const DATA_FILE = 'src/data/images/photos.ts'

interface Entry {
  lexemeId: string
  file: string
  reviewedAt: string
}

const ascii = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9-]/gi, '-').toLowerCase()

const manifest = JSON.parse(readFileSync('tools/images/commons-manifest.json', 'utf8')) as { photos: Entry[] }
const today = new Date().toISOString().slice(0, 10)
mkdirSync(OUT_DIR, { recursive: true })
mkdirSync('src/data/images', { recursive: true })

const records: string[] = []
const rejected: string[] = []
const CACHE = 'tools/images/.cache'
mkdirSync(CACHE, { recursive: true })

/** Metadata is cached per file so reruns do not hit the API again (delete the cache to refresh). */
async function cachedInfo(file: string): Promise<CommonsImage | null> {
  const path = join(CACHE, `${ascii(file)}.json`)
  if (existsSync(path)) return JSON.parse(readFileSync(path, 'utf8')) as CommonsImage
  const info = await imageInfo(file, THUMB)
  if (info) writeFileSync(path, JSON.stringify(info, null, 2))
  return info
}

for (const e of manifest.photos) {
  const info = await cachedInfo(e.file)
  if (!info) {
    rejected.push(`${e.lexemeId}: ${e.file} not found`)
    continue
  }
  const m = info.meta
  const licenseName = metaValue(m, 'LicenseShortName')
  const author = metaValue(m, 'Artist')
  const restrictions = metaValue(m, 'Restrictions')
  const problems = [
    !licenseName && 'no licence name',
    licenseName && !ACCEPTED.has(licenseName) && `licence "${licenseName}" is not on the accepted list`,
    !author && 'no author',
    /unknown author/i.test(author) && 'author unknown',
    restrictions && `restrictions: ${restrictions}`,
    !/^image\/(jpeg|png)$/.test(info.mime) && `type ${info.mime}`,
    !info.thumbUrl && 'no thumbnail',
  ].filter(Boolean)
  if (problems.length) {
    rejected.push(`${e.lexemeId}: ${e.file} — ${problems.join('; ')}`)
    continue
  }
  const ext = info.mime === 'image/png' ? 'png' : 'jpg'
  const fileName = `${ascii(e.lexemeId)}.${ext}`
  if (!existsSync(join(OUT_DIR, fileName))) {
    const res = await politeFetch(info.thumbUrl)
    if (!res.ok) {
      rejected.push(`${e.lexemeId}: thumbnail download failed (${res.status})`)
      continue
    }
    writeFileSync(join(OUT_DIR, fileName), Buffer.from(await res.arrayBuffer()))
  }
  const title = metaValue(m, 'ObjectName') || e.file.replace(/^File:/, '').replace(/\.[a-z]+$/i, '')
  const licenseUrl = metaValue(m, 'LicenseUrl')
  const attributionRequired = metaValue(m, 'AttributionRequired') === 'true'
  const providerAttribution = metaValue(m, 'Attribution')
  const credit = {
    provider: 'wikimedia-commons',
    sourceUrl: info.pageUrl,
    title,
    author,
    licenseName,
    ...(licenseUrl ? { licenseUrl } : {}),
    attributionRequired,
    // The provider's own attribution line when it gives one; otherwise title, author, licence and source.
    attributionText: providerAttribution || `“${title}” by ${author}, ${licenseName}, via Wikimedia Commons`,
    ...(metaValue(m, 'UsageTerms') ? { usageTerms: metaValue(m, 'UsageTerms') } : {}),
    modifications: `Resized to ${info.thumbWidth}×${info.thumbHeight} px (Wikimedia Commons thumbnail); otherwise unchanged.`,
    retrievedAt: today,
    reviewedAt: e.reviewedAt,
  }
  records.push(
    `  ${JSON.stringify(e.lexemeId)}: ${JSON.stringify({ src: `/images/nouns/${fileName}`, w: info.thumbWidth, h: info.thumbHeight, credit }, null, 2).replace(/\n/g, '\n  ')},`,
  )
  console.log(`✓ ${e.lexemeId}: ${licenseName} — ${author}`)
}

writeFileSync(
  DATA_FILE,
  `// Generated by tools/images/fetch-commons.ts from tools/images/commons-manifest.json — do not edit by hand.
// Every credit is copied from the file's own Wikimedia Commons metadata on the retrieval date.
import type { Image } from '../../types/content'

export const PHOTOS: Readonly<Record<string, NonNullable<Image['photo']>>> = {
${records.join('\n')}
}
`,
)
console.log(`\n${records.length} photos written to ${DATA_FILE}`)
if (rejected.length) {
  console.log(`\nRejected (${rejected.length}):\n  ${rejected.join('\n  ')}`)
  process.exitCode = 1
}
